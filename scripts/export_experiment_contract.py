"""Export C22 browser review types/schema from the authoritative public models."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pydantic.json_schema import models_json_schema
from schema.research_experiments import EXPERIMENT_REQUEST_MODELS, EXPERIMENT_RESPONSE_MODELS
from schema.experiment_workspace import EXECUTION_REQUEST_MODELS, EXECUTION_RESPONSE_MODELS
from scripts.export_catalogue_types import typescript

DIRECTORY = ROOT / 'frontend-v1/src/generated'


def export(requests, responses, source, prefix):
    models = list(dict.fromkeys([*requests.values(), *responses.values()]))
    _, schema = models_json_schema([(model, 'validation') for model in models])
    output = f'// Generated by scripts/export_experiment_contract.py from {source}. Do not edit by hand.\n'
    for name, definition in schema['$defs'].items():
        output += f'export type {name} = {typescript(definition)};\n\n'
    output += f'export type {prefix}Models = {{\n' + ''.join(
        f'  {json.dumps(name)}: {name};\n' for name in schema['$defs']) + '};\n'
    output += f'export const {"experimentContractSchema" if prefix == "Experiment" else "executionContractSchema"} = ' + json.dumps(
        schema, ensure_ascii=False, indent=2, sort_keys=True) + ' as const;\n'
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for filename, requests, responses, source, prefix in (
            ('experiment-review.generated.ts', EXPERIMENT_REQUEST_MODELS, EXPERIMENT_RESPONSE_MODELS, 'schema/research_experiments.py', 'Experiment'),
            ('experiment-execution.generated.ts', EXECUTION_REQUEST_MODELS, EXECUTION_RESPONSE_MODELS, 'schema/experiment_workspace.py', 'Execution')):
        target = DIRECTORY / filename
        expected = export(requests, responses, source, prefix)
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != expected:
                raise SystemExit(f'{filename} is stale; run scripts/export_experiment_contract.py')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected, encoding='utf-8')
    print('Experiment review/execution browser models/schema are current')


if __name__ == '__main__':
    main()
