"""Generate the v1 browser types and validation schema; use --check in CI."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "schema/context_catalogue.v1.schema.json"
TARGET = ROOT / "frontend-v1/src/catalogue-contract.generated.ts"


def typescript(node: dict | bool) -> str:
    """Translate the exported JSON Schema without maintaining a second model."""
    if isinstance(node, bool):
        return "unknown" if node else "never"
    if "$ref" in node:
        reference = node["$ref"]
        if not reference.startswith("#/$defs/"):
            raise ValueError(f"Unsupported catalogue schema reference: {reference}")
        return reference.rsplit("/", 1)[-1]
    if "const" in node:
        return json.dumps(node["const"], ensure_ascii=False)
    if "enum" in node:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in node["enum"])
    for union in ("anyOf", "oneOf"):
        if union in node:
            return "(" + " | ".join(typescript(value) for value in node[union]) + ")"
    if "allOf" in node:
        return "(" + " & ".join(typescript(value) for value in node["allOf"]) + ")"
    kind = node.get("type")
    if isinstance(kind, list):
        return "(" + " | ".join(typescript({**node, "type": item}) for item in kind) + ")"
    if kind == "object":
        required = node.get("required", [])
        properties = node.get("properties", {})
        members = [
            f"  {json.dumps(key)}{'' if key in required else '?'}: {typescript(value)};"
            for key, value in properties.items()
        ]
        additional = node.get("additionalProperties", True)
        if additional is not False:
            extra = "unknown" if additional is True else typescript(additional)
            if properties:
                return "({\n" + "\n".join(members) + "\n} & Record<string, " + extra + ">)"
            return "Record<string, " + extra + ">"
        return "{\n" + "\n".join(members) + "\n}"
    if kind == "array":
        if "prefixItems" in node:
            values = [typescript(value) for value in node["prefixItems"]]
            if node.get("items", True) is not False:
                rest = "unknown" if node.get("items", True) is True else typescript(node["items"])
                values.append("...(" + rest + ")[]")
            return "[" + ", ".join(values) + "]"
        return "(" + typescript(node.get("items", True)) + ")[]"
    primitives = {
        "string": "string", "integer": "number", "number": "number",
        "boolean": "boolean", "null": "null",
    }
    if kind in primitives:
        return primitives[kind]
    if not node or set(node) <= {"title", "description", "default"}:
        return "unknown"
    raise ValueError(f"Unsupported catalogue schema type: {node}")


def export() -> str:
    schema = json.loads(SOURCE.read_text())
    result = "// Generated by scripts/export_catalogue_types.py. Do not edit by hand.\n"
    result += "// Source: schema/context_catalogue.v1.schema.json.\n\n"
    for name, definition in schema.get("$defs", {}).items():
        result += f"export type {name} = {typescript(definition)};\n\n"
    result += f"export type CatalogueContract = {typescript(schema)};\n\n"
    result += "export type CatalogueModels = {\n"
    for name in schema.get("$defs", {}):
        result += f"  {json.dumps(name)}: {name};\n"
    result += "  CatalogueContract: CatalogueContract;\n};\n\n"
    result += "export const catalogueContractSchema = "
    result += json.dumps(schema, ensure_ascii=False, sort_keys=True, indent=2)
    result += " as const;\n"
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = export()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit("Catalogue browser contract is stale. Run scripts/export_catalogue_types.py.")
        print("Catalogue browser contract is current.")
    else:
        TARGET.write_text(expected)
        print(TARGET.relative_to(ROOT))


if __name__ == "__main__":
    main()
